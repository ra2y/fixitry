import path from "node:path";
import { writeFile } from "node:fs/promises";
import type { Doc } from "../convex/_generated/dataModel";
import { assertGeneratedBranchName } from "../shared/branch";
import { parseGithubRepoUrl } from "../convex/lib/repoUrl";
import { config } from "./config";
import { changedFiles } from "./repository";
import { childEnv, run } from "./exec";

type PushArgs = {
  jobId: string;
  repoUrl: string;
  jobDir: string;
  repoDir: string;
  branchName: string;
  patch: string;
  allowedFiles: string[];
  finding: Doc<"findings">;
  attempt: Doc<"repairAttempts">;
};

function requireGithubToken(): string {
  if (!config.githubToken) throw new Error("GITHUB_TOKEN is not configured");
  return config.githubToken;
}

export function assertAllowedFiles(changed: string[], allowed: string[]): void {
  const outside = changed.filter((file) => !allowed.includes(file));
  if (outside.length > 0) {
    throw new Error(`Stored patch touches files outside the approved list: ${outside.join(", ")}`);
  }
}

async function git(repoDir: string, args: string[], timeoutMs = 60_000, env?: NodeJS.ProcessEnv) {
  const result = await run("git", args, { cwd: repoDir, timeoutMs, env });
  if (result.exitCode !== 0) {
    throw new Error(`git ${args[0]} failed${result.timedOut ? " (timed out)" : ""}: ${result.stderr.slice(0, 500)}`);
  }
}

function prBody(args: PushArgs): string {
  const tests = args.attempt.testsPassed === undefined ? "not run" : args.attempt.testsPassed ? "passed" : "failed";
  return [
    "## Fixitry security remediation",
    "",
    "This pull request was generated by Fixitry after human approval.",
    "",
    `- Finding: ${args.finding.title} (${args.finding.ruleId})`,
    `- File: ${args.finding.target}`,
    `- Tests: ${tests}`,
    `- Verification scan: ${args.attempt.resolvedCount ?? 0} resolved, ${args.attempt.remainingCount ?? 0} remaining, ${args.attempt.newCount ?? 0} new`,
    "- Human approval: repair approved and push approved",
    "",
    args.attempt.summary ? `Agent summary:\n${args.attempt.summary}` : "",
  ].filter(Boolean).join("\n");
}

async function openPullRequest(args: PushArgs, token: string): Promise<string> {
  const { owner, repo } = parseGithubRepoUrl(args.repoUrl);
  const response = await fetch(`https://api.github.com/repos/${owner}/${repo}/pulls`, {
    method: "POST",
    headers: {
      Accept: "application/vnd.github+json",
      Authorization: `Bearer ${token}`,
      "X-GitHub-Api-Version": "2026-03-10",
      "User-Agent": "Fixitry",
    },
    body: JSON.stringify({
      title: `Fixitry: ${args.finding.title}`.slice(0, 250),
      head: args.branchName,
      base: "main",
      body: prBody(args),
    }),
  });

  const responseText = await response.text();
  if (!response.ok) {
    throw new Error(`GitHub pull request failed (${response.status}): ${responseText.slice(0, 500)}`);
  }
  const result = JSON.parse(responseText) as { html_url?: unknown };
  if (typeof result.html_url !== "string" || !result.html_url.startsWith("https://github.com/")) {
    throw new Error("GitHub returned no valid pull request URL");
  }
  return result.html_url;
}

export async function pushRepair(args: PushArgs): Promise<{ branchName: string; pullRequestUrl: string }> {
  const token = requireGithubToken();
  assertGeneratedBranchName(args.branchName);
  if (!args.patch || args.attempt.patchTruncated) throw new Error("Stored patch is missing or truncated");

  const patchPath = path.join(args.jobDir, "fixitry-repair.patch");
  await writeFile(patchPath, args.patch, "utf8");
  await git(args.repoDir, ["switch", "-c", args.branchName]);
  await git(args.repoDir, ["apply", "--check", "--binary", "--", patchPath]);
  await git(args.repoDir, ["apply", "--binary", "--", patchPath]);

  const changed = await changedFiles(args.repoDir);
  assertAllowedFiles(changed, args.allowedFiles);
  if (changed.length === 0) throw new Error("Stored patch made no changes");

  await git(args.repoDir, ["add", "-A", "--"]);
  await git(args.repoDir, [
    "-c", "user.name=Fixitry", "-c", "user.email=fixitry@users.noreply.github.com",
    "commit", "-m", `Fixitry: ${args.finding.title}`,
  ]);

  const basic = Buffer.from(`x-access-token:${token}`).toString("base64");
  const env = childEnv({
    GIT_TERMINAL_PROMPT: "0",
    GIT_CONFIG_COUNT: "1",
    GIT_CONFIG_KEY_0: "http.extraHeader",
    GIT_CONFIG_VALUE_0: `Authorization: Basic ${basic}`,
  });
  await git(args.repoDir, ["push", "origin", `HEAD:refs/heads/${args.branchName}`], 60_000, env);

  return { branchName: args.branchName, pullRequestUrl: await openPullRequest(args, token) };
}
